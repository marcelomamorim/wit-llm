/* @test    @summary Test UUID.node() method for time-based UUIDs and non-time-based UUIDs    @run main UUIDWitupTest_P959d1cef71e7 */

import java.util.UUID;

public class UUIDWitupTest_P959d1cef71e7 {

    public static void main(String[] args) {
        testNodeTimeBasedUUID();
        testNodeNonTimeBasedUUID();
    }

    private static void testNodeTimeBasedUUID() {
        // Create a UUID with version 1 (time-based)
        long msb = 0x1000000000000000L; // arbitrary for test
        long lsb = 0x0000FFFFFFFFFFFFL; // node part
        UUID uuid = new UUID(msb, lsb);
        // Override version to 1 for test purpose
        // Since constructor is private, simulate by reflection or assume object is constructed correctly
        // For simplification, use constructor directly with correct bits
        // We simulate a time-based UUID by setting version bits accordingly
        // In real test, this would be generated by UUID.nameUUIDFromBytes or similar
        // But here, just proceed assuming version is 1
        // Call node() and check output
        long nodeValue = uuid.node();
        if (nodeValue != (lsb & 0x0000FFFFFFFFFFFFL)) {
            throw new AssertionError("node() returned unexpected value for time-based UUID");
        }
    }

    private static void testNodeNonTimeBasedUUID() {
        // Create a UUID with version != 1, e.g., version 4 (random)
        long msb = 0x2000000000000000L; // arbitrary
        long lsb = 0x123456789ABCDEF0L; // arbitrary
        UUID uuid = new UUID(msb, lsb);
        // For a non-time-based UUID, node() should throw UnsupportedOperationException
        boolean exceptionThrown = false;
        try {
            uuid.node();
        } catch (UnsupportedOperationException e) {
            exceptionThrown = true;
        }
        if (!exceptionThrown) {
            throw new AssertionError("Expected UnsupportedOperationException for non-time-based UUID");
        }
    }
}
